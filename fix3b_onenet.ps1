# ---- 预校验: 每个块区域内, 被覆盖的行必须全部是乱码/注释/空行, 否则拒绝执行 ----
foreach ($start in ($map.Keys | Sort-Object)) {
    $v = $map[$start]
    $idx = $start - 1
    if (($idx + $v.Count) -gt $lines.Count) { throw "超出范围: 行 $start 需要 $($v.Count) 行" }
    for ($k = 0; $k -lt $v.Count; $k++) {
        $orig = $lines[$idx + $k]
        if ($orig -match '\?') { continue }
        if ($orig -match '^\s*$') { continue }
        if ($orig -match '^\s*[/\*]') { continue }
        throw "安全校验失败: 行 $($idx+$k+1) 不是注释/乱码, 可能覆盖代码: [$orig]"
    }
}

foreach ($start in ($map.Keys | Sort-Object)) {
    $v = $map[$start]
    $idx = $start - 1
    for ($k = 0; $k -lt $v.Count; $k++) {
        $lines[$idx + $k] = $v[$k]
    }
}

$out = $lines -join "`r`n"
[System.IO.File]::WriteAllBytes($path, $gbk.GetBytes($out))
Write-Output "onenet.c 注释修复完成, 共替换 $($map.Count) 个块"
