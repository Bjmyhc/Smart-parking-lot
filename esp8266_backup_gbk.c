/****************************************************************************
 * Function: ESP8266_Consume
 * Purpose:  Pop len bytes from the ring buffer (advance tail only).
 *           Unlike Clear(), it keeps the remaining bytes so a later
 *           GetIPD can return them. Enables incremental parsing when the
 *           buffer contains several MQTT packets / garbage + a real command.
 * Param:    len - number of bytes to drop
 * Return:   none
 ****************************************************************************/
void ESP8266_Consume(uint16_t len)
{
    uint16_t total = ESP8266_GetDataLen();
    __disable_irq();
    if (len > total)
        len = total;
    esp8266_rx.tail = (esp8266_rx.tail + len) % ESP8266_BUF_SIZE;
    __enable_irq();
}

