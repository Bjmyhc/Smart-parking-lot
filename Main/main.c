/****************************************************************************
 * 智能停车场系统 - 主程序入口
 *
 * 功能描述:
 *   基于STM32 + ESP8266实现的智能停车场车位检测系统
 *
 * 架构说明:
 *   main.c 仅作为程序入口，所有业务逻辑拆分到 App/ 层：
 *     - App/app_init.c     初始化函数 (BSP_Init, Wifi_Init)
 *     - App/app_tasks.c    周期任务函数 + 全局变量定义
 *     - App/app_global.h   全局变量声明
 *
 * 主循环流程(时间戳非阻塞架构):
 *   1. 超声波数据更新
 *   2. 地磁数据采集
 *   3. 车位状态检测
 *   4. LED控制
 *   5. OLED显示刷新
 *   6. WiFi通信: 数据上报 + 下行指令处理
 *
 * 作者: Bjmyhc
 * 日期: 2026-07-25
 ****************************************************************************/

#include "stm32f10x.h"
#include "app_global.h"
#include "app_init.h"
#include "app_tasks.h"

int main(void)
{
    /* 初始化所有板级外设(含LoRa模块) */
    BSP_Init();

    /* 主循环 - 时间戳非阻塞架构 */
    while (1)
    {
        US_Task();                  /* 超声波采样 */
        ParkingStatus_Check();      /* 车位状态检测 */
        QMC_Task();                 /* 地磁采集 */
        LED_Task();                 /* LED控制 */
        /* OLED_Task();  屏已移至网关集中显示, 节点改为纯采集上报(串口调试) */
        LoRa_Task();                /* LoRa通信: 响应网关轮询 + 下行命令 */
    }
}
