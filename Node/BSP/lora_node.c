static uint8_t LoRa_ParseCmd(LoRaCmdCallback cb)
{
    uint16_t i;
    char cmd[32];
    char value[32];
    char *pEq;
    uint16_t cmdLen;

    /* ?? \r\n */
    for (i = 0; i < s_rxLen; i++)
    {
        if (s_rxBuf[i] == '\r' && i + 1 < s_rxLen && s_rxBuf[i + 1] == '\n')
            break;
    }
    if (i >= s_rxLen)
        return 0;

    cmdLen = i;
    if (cmdLen >= sizeof(cmd))
        cmdLen = sizeof(cmd) - 1;
    memcpy(cmd, s_rxBuf, cmdLen);
    cmd[cmdLen] = '\0';

    /* ??????????????(??\r\n) */
    {
        uint16_t consumed = cmdLen + 2;
        memmove(s_rxBuf, s_rxBuf + consumed, s_rxLen - consumed);
        s_rxLen -= consumed;
    }

    /* ???? LoRa ????????????????????(?¿y¦Ë??? "Power on"):
     * ??????????¡¤??? AT ????, ?????????????, ????????,
     * ??????? LoRa ??????/??¦Ë??????? */
    if (strncmp(cmd, "AT", 2) != 0)
    {
        Usart_Printf(USART_DEBUG, "[LoRa] ??????: %s\r\n", cmd);
        return 1;
    }

    /* ???? AT ?????????, ????????????¡¤???? */
    Usart_Printf(USART_DEBUG, "[LoRa] ?????????: %s\r\n", cmd);

    /* ???????????????: AT+XXX=value */
    pEq = strchr(cmd, '=');
    if (pEq)
    {
        uint16_t vlen;
        *pEq = '\0';
        vlen = strlen(pEq + 1);
        if (vlen >= sizeof(value))
            vlen = sizeof(value) - 1;
        memcpy(value, pEq + 1, vlen);
        value[vlen] = '\0';
        cb(cmd, value);
    }
    else
    {
        cb(cmd, NULL);
    }

    return 1;
}

