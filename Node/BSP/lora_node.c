uint8_t LoRa_Node_Poll(LoRaCmdCallback cb)
{
    uint8_t processed = 0;
    uint16_t rxCount;

    /* ??????????? */
    rxCount = LoRa_ReadRx();

    /* ORE ???: ??? USART2 ???????????£ */
    if (usart2_oreCount != s_lastOreCount)
    {
        Usart_Printf(USART_DEBUG, "[LoRa][WARN] USART2 ORE! count=%d\r\n", usart2_oreCount);
        s_lastOreCount = usart2_oreCount;
    }

    /* ??????Ó: 30???????¦Ê????, ??? USART2 ??????§¿????? */
    if (rxCount > 0)
    {
        s_lastWarnTick = Get_Tick();
        s_noDataCycles = 0;
    }
    else if (s_lastWarnTick == 0)
    {
        s_lastWarnTick = Get_Tick();
    }
    else if ((Get_Tick() - s_lastWarnTick) >= 30000)
    {
        uint32_t sr = USART2->SR;
        uint32_t cr1 = USART2->CR1;
        Usart_Printf(USART_DEBUG,
            "[LoRa][WARN] 30s?????? SR=0x%04X CR1=0x%04X ISR=%lu ORE=%d\r\n",
            (unsigned int)sr, (unsigned int)cr1,
            (unsigned long)usart2_rxCount, usart2_oreCount);

        /* ???? 2 ??(60??)??????, ?????????? USART2 */
        s_noDataCycles++;
        if (s_noDataCycles >= 2)
        {
            Usart_Printf(USART_DEBUG, "[LoRa][WARN] 60s??????, ?????? USART2\r\n");
            Usart2_Init(LORA_BAUD);
            s_rxLen = 0;
            s_noDataCycles = 0;
        }
        s_lastWarnTick = Get_Tick();
    }

    /* ????????????????????? */
    while (LoRa_HasCompleteCmd())
    {
        if (LoRa_ParseCmd(cb))
            processed = 1;
    }

    return processed;
}

