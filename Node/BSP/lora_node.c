static uint16_t LoRa_ReadRx(void)
{
    uint16_t avail = sizeof(s_rxBuf) - 1 - s_rxLen;
    uint16_t count = 0;

    if (avail == 0)
        return 0;

    count = Usart2_GetData((uint8_t *)(s_rxBuf + s_rxLen), avail);
    s_rxLen += count;

    if (count > 0)
    {
        s_lastRxTick = Get_Tick();
        /* ????: ????? hex dump, ??????? OTA ??? LoRa ?????????? */
        for (uint16_t i = 0; i < count; i++)
        {
            uint8_t b = (uint8_t)s_rxBuf[s_rxLen - count + i];
            if (b >= 0x20 && b <= 0x7E)
                Usart_Printf(USART_DEBUG, "%c", b);
            else
                Usart_Printf(USART_DEBUG, "[%02X]", b);
        }
    }

    return count;
}

