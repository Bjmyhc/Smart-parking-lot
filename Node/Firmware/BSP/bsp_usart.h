﻿/****************************************************************************
 * 串口驱动头文件 - bsp_usart.h
 * 
 * 功能描述:
 *   提供STM32串口初始化、数据发送和格式化打印功能
 *   支持USART1(调试串口)、USART2(LoRa 模块通信串口)、USART3(摄像头通信串口)
 * 
 * 硬件配置:
 *   - USART1: PA9(TX), PA10(RX) - 调试串口
 *   - USART2: PA2(TX), PA3(RX) - LoRa 模块通信串口(9600)
 *   - USART3: PB10(TX), PB11(RX) - ESP32-S3 摄像头模组通信串口(115200)
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef BSP_USART_H
#define BSP_USART_H

#include "stm32f10x.h"
#include <stdio.h>


/* 调试打印使用的串口号 */
#define USART_DEBUG		USART1

/* USART2 环形缓冲区大小 */
#define USART2_RBUF_SIZE	256

/* USART3 环形缓冲区大小 */
#define USART3_RBUF_SIZE	256

/* ⭐ USART2 ISR 诊断计数器(extern 声明, 定义在 bsp_usart.c):
 *   usart2_oreCount  - ORE 溢出错误次数(持续增长说明串口过载/中断被阻塞)
 *   usart2_rxCount   - ISR 累计接收字节数(停止增长说明 RX 中断没触发)
 * 主循环周期打印用于定位"LoRa 模块有输出但 STM32 收不到"类故障 */
extern volatile uint16_t usart2_oreCount;
extern volatile uint32_t usart2_rxCount;

/* ⭐ USART3 ISR 诊断计数器(摄像头串口), 含义同 usart2_* */
extern volatile uint16_t usart3_oreCount;
extern volatile uint32_t usart3_rxCount;

/****************************************************************************
 * 函数名: Usart1_Init
 * 功能:   初始化USART1
 * 参数:   baud - 波特率
 * 返回值: 无
 ****************************************************************************/
void Usart1_Init(unsigned int baud);

/****************************************************************************
 * 函数名: Usart2_Init
 * 功能:   初始化USART2
 * 参数:   baud - 波特率
 * 返回值: 无
 ****************************************************************************/
void Usart2_Init(unsigned int baud);

/****************************************************************************
 * 函数名: Usart_SendString
 * 功能:   发送字符串
 * 参数:   USARTx - 串口号
 *         str - 字符串指针
 *         len - 字符串长度
 * 返回值: 无
 ****************************************************************************/
void Usart_SendString(USART_TypeDef *USARTx, unsigned char *str, unsigned short len);

/****************************************************************************
 * 函数名: Usart_Printf
 * 功能:   格式化打印(类似printf)
 * 参数:   USARTx - 串口号
 *         fmt - 格式化字符串
 * 返回值: 无
 ****************************************************************************/
void Usart_Printf(USART_TypeDef *USARTx, char *fmt,...);

/****************************************************************************
 * 函数名: Usart_Init
 * 功能:   初始化所有串口
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void Usart_Init(void);

/****************************************************************************
 * 函数名: Usart2_GetData
 * 功能:   从USART2环形缓冲区读取数据
 * 参数:   buf    - 接收缓冲区
 *         maxlen - 最大读取长度
 * 返回值: 实际读取的字节数
 ****************************************************************************/
uint16_t Usart2_GetData(uint8_t *buf, uint16_t maxlen);

/* ==================== USART2 发送(DMA 非阻塞) ====================
 * ⭐ 原 Usart_SendString(USART2,...) 逐字节等 TC, 一帧(19~70B)会把主循环
 *   阻塞约 20~73ms(9600bps). 改为 DMA1_Channel7(USART2_TX) 搬运:
 *   调用即把整帧拷入内部发送缓冲并启动 DMA, 立即返回, 传输在后台继续.
 *
 * 注意:
 *   1) DMA 搬运期间内部缓冲必须保持有效, 故调用者传入的缓冲会被
 *      **先拷贝**到内部静态缓冲, 调用者可继续复用/离开作用域;
 *   2) 内部缓冲只有一份: 若上一帧尚未搬完, 本函数会先等它结束
 *      (节点每轮才回一帧, 正常此处耗时为 0);
 *   3) 本函数返回不代表"已发完", 仅代表"已开始发送". 需查询完成
 *      与否请用 Usart2_TxBusy(). */

/****************************************************************************
 * 函数名: Usart2_SendAsync
 * 功能:   USART2 非阻塞发送(DMA 搬运), 启动后立即返回
 * 参数:   data - 待发送数据指针(会被拷入内部缓冲)
 *         len  - 数据长度(超过内部缓冲上限则截断)
 * 返回值: 无
 ****************************************************************************/
void Usart2_SendAsync(const uint8_t *data, uint16_t len);

/****************************************************************************
 * 函数名: Usart2_TxBusy
 * 功能:   查询上一帧 DMA 是否仍在发送中
 * 参数:   无
 * 返回值: 1=仍在搬运; 0=已完成/空闲
 ****************************************************************************/
uint8_t Usart2_TxBusy(void);

/* ==================== USART3 (摄像头模组, PB10/PB11 @115200) ====================
 * 与 USART2 同范式: RX 走 RXNE 中断进环形缓冲, TX 走 DMA1_Channel2 非阻塞搬运。
 * 优先级刻意低于 USART2(LoRa 收字节不能被延后) */

/****************************************************************************
 * 函数名: Usart3_Init
 * 功能:   初始化USART3
 * 参数:   baud - 波特率
 * 返回值: 无
 * 引脚:   TX-PB10, RX-PB11
 ****************************************************************************/
void Usart3_Init(unsigned int baud);

/****************************************************************************
 * 函数名: Usart3_GetData
 * 功能:   从USART3环形缓冲区读取数据(非阻塞)
 * 参数:   buf    - 接收缓冲区
 *         maxlen - 最大读取长度
 * 返回值: 实际读取的字节数 (0=缓冲区空)
 ****************************************************************************/
uint16_t Usart3_GetData(uint8_t *buf, uint16_t maxlen);

/****************************************************************************
 * 函数名: Usart3_SendAsync
 * 功能:   USART3 非阻塞发送(DMA1_Channel2 搬运), 启动后立即返回
 * 参数:   data - 待发送数据指针(会先拷入内部静态缓冲)
 *         len  - 数据长度(超过内部缓冲上限则截断)
 * 返回值: 无
 ****************************************************************************/
void Usart3_SendAsync(const uint8_t *data, uint16_t len);

/****************************************************************************
 * 函数名: Usart3_TxBusy
 * 功能:   查询上一帧 DMA 是否仍在发送中
 * 参数:   无
 * 返回值: 1=仍在搬运; 0=已完成/空闲
 ****************************************************************************/
uint8_t Usart3_TxBusy(void);

/****************************************************************************
 * 函数名: Usart3_FlushRx
 * 功能:   清空 USART3 接收环形缓冲(发新命令前丢弃残留回显/旧结果)
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void Usart3_FlushRx(void);

#endif
