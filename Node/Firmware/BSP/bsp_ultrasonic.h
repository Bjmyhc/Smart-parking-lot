/****************************************************************************
 * 超声波传感器驱动头文件 - bsp_ultrasonic.h
 * 
 * 功能描述:
 *   提供HC-SR04超声波传感器的初始化和距离测量功能
 *   通过定时器测量回波时间计算距离
 * 
 * 硬件配置:
 *   - 定时器: TIM1(72MHz,输入捕获模式)
 *   - 触发引脚: PB15(Trig, 推挽输出)
 *   - 回波引脚: PA8(Echo, TIM1_CH1输入捕获)
 *   - 测量范围: 2cm - 400cm
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef ULTRASONIC_H
#define ULTRASONIC_H

#include "stm32f10x.h"

/* 触发引脚(Trig) - PA0 */
#define US_TRIG_CLK     RCC_APB2Periph_GPIOB
#define US_TRIG_PORT    GPIOB
#define US_TRIG_PIN     GPIO_Pin_15

/* 回波引脚(Echo) - PA8 (TIM1_CH1输入捕获) */
#define US_ECHO_CLK     RCC_APB2Periph_GPIOA
#define US_ECHO_PORT    GPIOA
#define US_ECHO_PIN     GPIO_Pin_8

/****************************************************************************
 * 函数名: US_Init
 * 功能:   初始化超声波传感器
 * 参数:   无
 * 返回值: 无
 * 说明:   配置定时器TIM1为输入捕获模式
 ****************************************************************************/
void US_Init(void);

/* ==================== 非阻塞测量接口 ====================
 * 原阻塞式 US_GetDistance()(最坏 200ms+200ms 忙等回波)已改为
 * "启动 + 轮询"两段式:
 *   US_StartMeasure() 复位计数/发触发脉冲后立即返回;
 *   US_Poll() 由主循环每轮调用一次推进状态机, 完成时才给结果.
 * 好处: 不再忙等回波, 主循环单圈不再被 200~400ms 阻塞. */

/* US_Poll 返回码 */
#define US_MEAS_NONE     0U   /* 空闲或测量进行中, 无新结果 */
#define US_MEAS_DONE     1U   /* 测量完成, *outDistCm 有效 */
#define US_MEAS_TIMEOUT  2U   /* 本次超时(无回波/回波不完整), 无新结果 */

/* 单段等待超时(ms): 等回波上升沿/下降沿各自的上限 */
#define US_ECHO_TIMEOUT_MS   200U

/****************************************************************************
 * 函数名: US_StartMeasure
 * 功能:   启动一次超声波测量(非阻塞)
 * 参数:   无
 * 返回值: 1=已启动; 0=上一次测量尚未结束, 本次跳过(不重入)
 * 说明:   复位计数/清捕获标志/开TIM1/发15µs触发脉冲, 随后立即返回
 ****************************************************************************/
uint8_t US_StartMeasure(void);

/****************************************************************************
 * 函数名: US_Poll
 * 功能:   轮询推进测量状态机(非阻塞)
 * 参数:   outDistCm - 测量完成时写入原始距离(cm)
 * 返回值: US_MEAS_NONE / US_MEAS_DONE / US_MEAS_TIMEOUT
 * 说明:   主循环每轮调用一次; 仅 US_MEAS_DONE 时写入 outDistCm
 ****************************************************************************/
uint8_t US_Poll(uint16_t *outDistCm);

#endif
