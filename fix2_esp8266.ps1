# 逐行替换
foreach ($start in ($map.Keys | Sort-Object)) {
    $newLines = $map[$start]
    $idx = $start - 1
    if (($idx + $newLines.Count) -gt $lines.Count) { throw "超出范围: 行 $start 需要 $($newLines.Count) 行" }
    for ($k = 0; $k -lt $newLines.Count; $k++) {
        $lines[$idx + $k] = $newLines[$k]
    }
}

$out = $lines -join "`r`n"
