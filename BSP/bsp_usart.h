/****************************************************************************
 * 串口驱动头文件 - bsp_usart.h
 * 
 * 功能描述:
 *   提供STM32串口初始化、数据发送和格式化打印功能
 *   支持USART1(调试串口)和USART2(ESP8266通信串口)
 * 
 * 硬件配置:
 *   - USART1: PA9(TX), PA10(RX) - 调试串口
 *   - USART2: PA2(TX), PA3(RX) - ESP8266通信串口
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef BSP_USART_H
#define BSP_USART_H

#include "stm32f10x.h"
#include <stdio.h>


/* 调试打印使用的串口号 */
#define USART_DEBUG		USART1		

/****************************************************************************
 * 函数名: Usart1_Init
 * 功能:   初始化USART1
 * 参数:   baud - 波特率
 * 返回值: 无
 ****************************************************************************/
void Usart1_Init(unsigned int baud);

/****************************************************************************
 * 函数名: Usart2_Init
 * 功能:   初始化USART2
 * 参数:   baud - 波特率
 * 返回值: 无
 ****************************************************************************/
void Usart2_Init(unsigned int baud);

/****************************************************************************
 * 函数名: Usart_SendString
 * 功能:   发送字符串
 * 参数:   USARTx - 串口号
 *         str - 字符串指针
 *         len - 字符串长度
 * 返回值: 无
 ****************************************************************************/
void Usart_SendString(USART_TypeDef *USARTx, unsigned char *str, unsigned short len);

/****************************************************************************
 * 函数名: Usart_Printf
 * 功能:   格式化打印(类似printf)
 * 参数:   USARTx - 串口号
 *         fmt - 格式化字符串
 * 返回值: 无
 ****************************************************************************/
void Usart_Printf(USART_TypeDef *USARTx, char *fmt,...);

/****************************************************************************
 * 函数名: Usart_Init
 * 功能:   初始化所有串口
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void Usart_Init(void);

#endif