/****************************************************************************
 * QMC5883L地磁传感器驱动头文件 - bsp_qmc5883.h
 * 
 * 功能描述:
 *   提供QMC5883L三轴磁传感器的初始化和数据读取功能
 *   用于检测地磁场变化，判断车位是否有车辆
 * 
 * 硬件配置:
 *   - I2C接口通信
 *   - 测量范围: ±8Gauss
 *   - 输出数据率: 100Hz
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef QMC5883L_H
#define QMC5883L_H

#include "stm32f10x.h"

/****************************************************************************
 * 函数名: QMC_Init
 * 功能:   初始化QMC5883L地磁传感器
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void QMC_Init(void);

/****************************************************************************
 * 函数名: QMC_ReadRaw
 * 功能:   读取原始地磁数据
 * 参数:   x - X轴数据指针
 *         y - Y轴数据指针
 *         z - Z轴数据指针
 * 返回值: 无
 ****************************************************************************/
void QMC_ReadRaw(int16_t *x, int16_t *y, int16_t *z);

#endif