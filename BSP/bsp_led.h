/****************************************************************************
 * LED驱动头文件 - bsp_led.h
 * 
 * 功能描述:
 *   提供LED灯的初始化和开关控制功能
 *   用于系统状态指示和调试
 * 
 * 硬件配置:
 *   - LED: PA0 - 推挽输出
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef BSP_LED_H
#define BSP_LED_H

#include "stm32f10x.h"

/* LED硬件配置 */
#define LED_GPIO_PORT GPIOA
#define LED_GPIO_CLK  RCC_APB2Periph_GPIOA
#define LED_GPIO_PIN  GPIO_Pin_0

/****************************************************************************
 * 函数名: LED_Init
 * 功能:   初始化LED引脚
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void LED_Init(void);

/****************************************************************************
 * 函数名: LED_ON
 * 功能:   点亮LED
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void LED_ON(void);

/****************************************************************************
 * 函数名: LED_OFF
 * 功能:   熄灭LED
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void LED_OFF(void);

/****************************************************************************
 * 函数名: LED_GetState
 * 功能:   获取LED状态
 * 参数:   无
 * 返回值: 0=熄灭, 1=点亮
 ****************************************************************************/
uint8_t LED_GetState(void);

#endif
