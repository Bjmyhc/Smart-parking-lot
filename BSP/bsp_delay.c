/****************************************************************************
 * 延时驱动 - bsp_delay.c
 * 
 * 功能描述:
 *   实现系统滴答定时器和软件延时函数
 *   SysTick定时器提供1ms精度的系统计时
 *   软件延时提供微秒级延时能力
 * 
 * 硬件配置:
 *   - SysTick定时器: 72MHz系统时钟, 1ms中断周期
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/

#include "bsp_delay.h"

/* 系统滴答计数变量(毫秒) */
volatile uint32_t sys_tick = 0;

/****************************************************************************
 * 函数名: SysTick_Handler
 * 功能:   SysTick定时器中断服务函数
 * 参数:   无
 * 返回值: 无
 * 说明:   每次中断(1ms)系统滴答计数加1
 ****************************************************************************/
void SysTick_Handler(void)
{
    sys_tick++;
}

/****************************************************************************
 * 函数名: Get_Tick
 * 功能:   获取系统滴答计数
 * 参数:   无
 * 返回值: 当前系统滴答值(单位:毫秒)
 * 用途:   用于定时判断、时间戳记录等
 ****************************************************************************/
uint32_t Get_Tick(void)
{
    return sys_tick;
}

/****************************************************************************
 * 函数名: SysTick_Init
 * 功能:   初始化系统滴答定时器
 * 参数:   无
 * 返回值: 无
 * 说明:   配置SysTick定时器,1ms中断一次
 *         装载值 = SystemCoreClock / 1000 = 72000
 ****************************************************************************/
void SysTick_Init(void)
{
    if (SysTick_Config(SystemCoreClock / 1000) != 0)
    {
        while (1);
    }
}

/****************************************************************************
 * 函数名: DelayXus
 * 功能:   微秒级软件延时
 * 参数:   time - 延时时间(微秒)
 * 返回值: 无
 * 说明:   通过循环实现的软件延时,精度依赖CPU频率
 ****************************************************************************/
void DelayXus(uint32_t time)
{
    while (time--)
    {
        delay_1us();
    }
}

/****************************************************************************
 * 函数名: DelayXms
 * 功能:   毫秒级软件延时
 * 参数:   time - 延时时间(毫秒)
 * 返回值: 无
 * 说明:   通过微秒延时循环实现,精度依赖CPU频率
 *         注意:不推荐在中断中使用此函数
 ****************************************************************************/
void DelayXms(uint32_t time)
{
    uint64_t t = time * 1000;
    while (t--)
    {
        delay_1us();
    }
}
