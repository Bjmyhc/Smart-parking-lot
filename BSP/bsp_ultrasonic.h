/****************************************************************************
 * 超声波传感器驱动头文件 - bsp_ultrasonic.h
 * 
 * 功能描述:
 *   提供HC-SR04超声波传感器的初始化和距离测量功能
 *   通过定时器测量回波时间计算距离
 * 
 /* 硬件配置:
 *   - 定时器: TIM1(72MHz,输入捕获模式)
 *   - 触发引脚: PA0(Trig, 推挽输出)
 *   - 回波引脚: PA8(Echo, TIM1_CH1输入捕获)
 *   - 测量范围: 2cm - 400cm
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef ULTRASONIC_H
#define ULTRASONIC_H

#include "stm32f10x.h"

/* 触发引脚(Trig) - PA0 */
#define US_TRIG_CLK     RCC_APB2Periph_GPIOB
#define US_TRIG_PORT    GPIOB
#define US_TRIG_PIN     GPIO_Pin_15

/* 回波引脚(Echo) - PA8 (TIM1_CH1输入捕获) */
#define US_ECHO_CLK     RCC_APB2Periph_GPIOA
#define US_ECHO_PORT    GPIOA
#define US_ECHO_PIN     GPIO_Pin_8

/****************************************************************************
 * 函数名: US_Init
 * 功能:   初始化超声波传感器
 * 参数:   无
 * 返回值: 无
 * 说明:   配置定时器TIM4为输入捕获模式
 ****************************************************************************/
void US_Init(void);

/****************************************************************************
 * 函数名: US_GetDistance
 * 功能:   获取测量距离(原始值)
 * 参数:   无
 * 返回值: 距离值(单位: cm)
 * 说明:   通过测量回波时间计算距离
 *         距离 = (回波时间 * 声速) / 2
 ****************************************************************************/
uint16_t US_GetDistance(void);

#endif
