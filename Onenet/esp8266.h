/****************************************************************************
 * ESP8266 WiFi模块驱动头文件 - esp8266.h
 * 
 * 功能描述:
 *   提供ESP8266 WiFi模块的初始化、命令发送和数据接收功能
 *   使用环形缓冲区管理接收数据，支持非阻塞式数据读取
 * 
 * 硬件配置:
 *   - USART2: PA2(TX), PA3(RX)
 *   - 波特率: 115200
 *   - 环形缓冲区大小: 512字节
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef _ESP8266_H_
#define _ESP8266_H_

/* 接收状态标志 */
#define REV_OK		0	//接收完成标志
#define REV_WAIT	1	//接收未完成标志

/* 环形缓冲区大小 */
#define ESP8266_BUF_SIZE	512

/****************************************************************************
 * 结构体: ESP8266_RxBuffer_t
 * 功能:   环形缓冲区管理结构体
 * 成员:   head - 写指针（中断写入）
 *         tail - 读指针（主循环读取）
 *         overflow - 溢出标志
 ****************************************************************************/
typedef struct {
    volatile uint16_t head;     // 写指针（中断写入）
    volatile uint16_t tail;     // 读指针（主循环读取）
    volatile uint8_t overflow;  // 溢出标志
} ESP8266_RxBuffer_t;

/****************************************************************************
 * 函数名: ESP8266_Init
 * 功能:   初始化ESP8266模块
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void ESP8266_Init(void);

/****************************************************************************
 * 函数名: ESP8266_Clear
 * 功能:   清空接收缓冲区
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void ESP8266_Clear(void);

/****************************************************************************
 * 函数名: ESP8266_SendCmd
 * 功能:   发送AT命令并等待响应
 * 参数:   cmd - AT命令字符串
 *         res - 期望的响应字符串
 * 返回值: 0-成功, 1-失败
 ****************************************************************************/
_Bool ESP8266_SendCmd(char *cmd, char *res);

/****************************************************************************
 * 函数名: ESP8266_SendData
 * 功能:   发送数据到ESP8266
 * 参数:   data - 数据指针
 *         len - 数据长度
 * 返回值: 无
 ****************************************************************************/
void ESP8266_SendData(unsigned char *data, unsigned short len);

/****************************************************************************
 * 函数名: ESP8266_GetIPD
 * 功能:   获取ESP8266接收到的数据
 * 参数:   timeOut - 超时时间(单位: 5ms)
 * 返回值: 数据指针(指向缓冲区), NULL表示超时
 ****************************************************************************/
unsigned char *ESP8266_GetIPD(unsigned short timeOut);

/****************************************************************************
 * 函数名: ESP8266_GetDataLen
 * 功能:   获取缓冲区数据长度
 * 参数:   无
 * 返回值: 缓冲区中数据长度
 ****************************************************************************/
uint16_t ESP8266_GetDataLen(void);

/****************************************************************************
 * 函数名: ESP8266_IsOverflow
 * 功能:   检查缓冲区是否溢出
 * 参数:   无
 * 返回值: 1-溢出, 0-未溢出
 ****************************************************************************/
uint8_t ESP8266_IsOverflow(void);

/****************************************************************************
 * 函数名: ESP8266_ClearOverflow
 * 功能:   清除溢出标志
 * 参数:   无
 * 返回值: 无
 ****************************************************************************/
void ESP8266_ClearOverflow(void);

#endif
