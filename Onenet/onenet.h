/****************************************************************************
 * OneNET云平台通信驱动头文件 - onenet.h
 * 
 * 功能描述:
 *   提供与OneNET云平台的MQTT协议通信接口
 *   支持设备连接、属性上报、指令接收等功能
 * 
 * 硬件配置:
 *   - 通过ESP8266 WiFi模块连接OneNET平台
 *   - 使用MQTT协议(1883端口)
 * 
 * 设备认证信息:
 *   - 产品ID: 53BV12EYcY
 *   - 设备名称: park1
 * 
 * 作者: Bjmyhc
 * 日期: 2026-07-19
 ****************************************************************************/
#ifndef _ONENET_H_
#define _ONENET_H_

/****************************************************************************
 * 函数名: OneNet_DevLink
 * 功能:   连接OneNET云平台
 * 参数:   无
 * 返回值: 0-连接成功, 1-连接失败
 * 说明:   使用MQTT协议连接OneNET平台
 *         连接参数: 产品ID, Token, 设备名称
 *         超时时间约250×5ms = 1.25秒
 ****************************************************************************/
_Bool OneNet_DevLink(void);

/****************************************************************************
 * 函数名: OneNet_Subscribe
 * 功能:   订阅OneNET平台主题
 * 参数:   topics - 主题数组指针
 *         topic_cnt - 主题数量
 * 返回值: 无
 * 说明:   订阅平台下发指令的主题
 *         使用QOS Level 0
 ****************************************************************************/
void OneNet_Subscribe(const char *topics[], unsigned char topic_cnt);

/****************************************************************************
 * 函数名: OneNet_RevPro
 * 功能:   处理平台下发的指令
 * 参数:   cmd - 接收到的原始MQTT数据包
 * 返回值: 无
 * 说明:   解析MQTT数据包,处理各种类型的消息
 *         包括: CMD指令、PUBLISH消息、PUBACK确认等
 ****************************************************************************/
void OneNet_RevPro(unsigned char *cmd);

/****************************************************************************
 * 函数名: OneNet_Publish
 * 功能:   发布消息到OneNET平台
 * 参数:   topic - 发布主题
 *         msg - 消息内容(JSON格式)
 * 返回值: 无
 * 说明:   使用QOS Level 0发布消息
 *         消息保留标志: 1(保留)
 ****************************************************************************/
void OneNet_Publish(const char *topic, const char *msg);

#endif
